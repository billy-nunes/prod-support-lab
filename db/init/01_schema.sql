-- Shop schema.
-- Some indexes are DELIBERATELY missing so you have real performance problems to find:
--   orders(customer_id), orders(created_at), order_items(order_id), settlements(order_id) UNIQUE
-- Do not add them here. Add them later as migrations in db/migrations/ (see docs/CURRICULUM.md).

CREATE TABLE customers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text        NOT NULL,
    full_name     text        NOT NULL,
    loyalty_tier  text        NOT NULL CHECK (loyalty_tier IN ('bronze','silver','gold')),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX customers_email_key ON customers (email);

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text    NOT NULL UNIQUE,
    name         text    NOT NULL,
    category     text    NOT NULL,
    price_pence  integer NOT NULL CHECK (price_pence > 0)
);

CREATE TABLE inventory (
    product_id  bigint PRIMARY KEY REFERENCES products(id),
    qty         integer NOT NULL CHECK (qty >= 0),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orders (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       bigint      NOT NULL,
    status            text        NOT NULL,
    currency          text        NOT NULL DEFAULT 'GBP',
    total_pence       integer     NOT NULL,
    shipping_address  text        NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          bigint  NOT NULL,
    product_id        bigint  NOT NULL,
    qty               integer NOT NULL,
    unit_price_pence  integer NOT NULL
);

CREATE TABLE audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event       text NOT NULL,
    req_id      text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Written by the settlement worker. Note: no unique constraint on order_id.
CREATE TABLE settlements (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint      NOT NULL,
    amount_pence  integer     NOT NULL,
    currency      text        NOT NULL,
    run_id        bigint      NOT NULL,
    settled_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE job_runs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job              text        NOT NULL,
    status           text        NOT NULL CHECK (status IN ('running','success','failed')),
    started_at       timestamptz NOT NULL DEFAULT now(),
    heartbeat_at     timestamptz NOT NULL DEFAULT now(),
    finished_at      timestamptz,
    rows_processed   integer     NOT NULL DEFAULT 0,
    high_water_mark  bigint,
    error            text
);
